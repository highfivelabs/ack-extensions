# Every Go file and shell script we wrote or copied names its licence with
# an SPDX line near the top. Files the generators write (ack-generate's and
# controller-gen's headers) carry the generator's own header instead.
set -o errexit -o nounset -o pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT}"
missing=0
while IFS= read -r f; do
  [[ -f "${f}" ]] || continue
  # ack-generate writes apis/<version>/doc.go without any header.
  [[ "${f}" == services/*/apis/*/doc.go ]] && continue
  head -n 30 "${f}" | grep -q -e 'Code generated by ack-generate. DO NOT EDIT.' -e 'Code generated by controller-gen. DO NOT EDIT.' && continue
  if ! head -n 30 "${f}" | grep -q 'SPDX-License-Identifier: Apache-2.0'; then
    echo "no SPDX-License-Identifier line: ${f}" >&2
    missing=$((missing + 1))
  fi
done < <(git ls-files --cached --others --exclude-standard -- '*.go' '*.sh')
[[ ${missing} -eq 0 ]] || { echo "${missing} file(s) without an SPDX line" >&2; exit 1; }
echo "ok: every Go file and shell script has an SPDX line or a generator's header"
