// Command cloudcontrol-gen generates everything per type that the generic
// Cloud Control manager needs, from CloudFormation registry schemas:
//
//	go run ./hack/cloudcontrol-gen            # the types in cloudcontrol/types.yaml
//	go run ./hack/cloudcontrol-gen --survey   # every type in the zip: cloudcontrol/readiness.{csv,md}
//
// Per type it writes the CRD (cloudcontrol/config/crds), the schema the
// reconciler embeds and the registry entry (cloudcontrol/pkg/registry), the
// least-privilege IAM policy (cloudcontrol/config/iam) and, for all types,
// the manager's ClusterRole (cloudcontrol/config/rbac) and a generation
// report (cloudcontrol/zz_generated.report.md). It never talks to AWS: the
// schemas come from the zip committed for the coverage dashboard.
package main

