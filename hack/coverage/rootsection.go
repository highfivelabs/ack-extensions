// rootSection is the text between the markers in the root README.md.
func rootSection(r *results) string {
	t := r.total
	var b strings.Builder
	b.WriteString("## Coverage\n\n")
	fmt.Fprintf(&b, "How much of AWS the official ACK controllers cover, and how much more this repository adds, counted in writable CloudFormation resource properties (\"attributes\") per service. Generated by `hack/coverage/run.sh`; the method, pinned sources and caveats are in [docs/coverage/README.md](docs/coverage/README.md).\n\n")
	fmt.Fprintf(&b, "![Total coverage. Attributes: official %s%%, ours beyond official %s%%, uncovered %s%%. Resources: official %s%%, ours beyond official %s%%, uncovered %s%%.](docs/coverage/bars/_total.svg)\n\n",
		pct1(t.attrOfficial, t.attrTotal), pct1(t.attrOursBeyond, t.attrTotal), pct1(t.attrUncov, t.attrTotal),
		pct1(t.resOfficial, t.resTotal), pct1(t.resOursBeyond, t.resTotal), pct1(t.resTotal-t.resOfficial-t.resOursBeyond, t.resTotal))
	big := r.svcs[0]
	for _, s := range r.svcs {
		if s.attrTotal > big.attrTotal {
			big = s
		}
	}
	fmt.Fprintf(&b, "`%s` alone is %s of the %s attributes, so the attribute bar mostly describes it; the resource bar counts a resource as covered if ACK has a kind for it, however few of its fields.\n\n", big.service, commas(big.attrTotal), commas(t.attrTotal))
	fmt.Fprintf(&b, "Of %s attributes in %d resources across %d services, ACK covers %s (%s%%) and ours adds %s more (%s%%)",
		commas(t.attrTotal), t.resTotal, len(r.svcs), commas(t.attrOfficial), pct1(t.attrOfficial, t.attrTotal), commas(t.attrOursBeyond), pct1(t.attrOursBeyond, t.attrTotal))
	if t.oursBeyondPR > 0 {
		fmt.Fprintf(&b, ", %s of them copied from open upstream pull requests", commas(t.oursBeyondPR))
	}
	fmt.Fprintf(&b, ". By resource, ACK has a released kind for %d of %s (%s%%) and ours adds %d more (%s%%).\n\n", t.resOfficial, commas(t.resTotal), pct1(t.resOfficial, t.resTotal), t.resOursBeyond, pct1(t.resOursBeyond, t.resTotal))

	var covered []svcRow
	for _, s := range r.svcs {
		if s.attrOfficial+s.attrOursBeyond > 0 || s.resOfficial+s.resOursBeyond > 0 {
			covered = append(covered, s)
		}
	}
	sort.SliceStable(covered, func(i, j int) bool {
		ti, tj := r.tierOf(covered[i].service), r.tierOf(covered[j].service)
		if ti != tj {
			return ti < tj
		}
		ci, cj := covered[i].attrOfficial+covered[i].attrOursBeyond, covered[j].attrOfficial+covered[j].attrOursBeyond
		if ci != cj {
			return ci > cj
		}
		return covered[i].service < covered[j].service
	})

	tiers := r.tierRows()
	b.WriteString("Not every service matters equally, so services are in three tiers by how much a team migrating from Terraform needs them: tier 1 is what the ten most-downloaded terraform-aws-modules use (iam, s3, vpc and security groups, eks, kms, lambda, rds, acm), tier 2 every other service some tracked module uses, tier 3 everything else ([how and why](docs/coverage/README.md#tiers); the list is the hand-editable [priority.csv](docs/coverage/priority.csv)). Upper bar of each pair: attributes; lower: resources.\n\n")
	b.WriteString("![Coverage by tier](docs/coverage/bars/_tiers.svg)\n\n")
	b.WriteString("| Tier | Services | Resources (ACK / ours beyond) | Attributes (ACK / ours beyond) |\n| --- | ---: | ---: | ---: |\n")
	for _, t := range tiers {
		fmt.Fprintf(&b, "| %d | %d | %s%% / %s%% | %s%% / %s%% |\n", t.tier, t.services, pct1(t.resOfficial, t.resTotal), pct1(t.resOursBeyond, t.resTotal), pct1(t.attrOfficial, t.attrTotal), pct1(t.attrOursBeyond, t.attrTotal))
	}
	b.WriteString("\n")

	row := func(s svcRow) string {
		return fmt.Sprintf("| %d | `%s` | ![%s](docs/coverage/bars/%s.svg) | %s%% | %s%% | %s%% |\n", r.tierOf(s.service), s.service, s.service, s.service,
			pct1(s.attrOfficial, s.attrTotal), pct1(s.attrOursBeyond, s.attrTotal), pct1(s.attrUncov, s.attrTotal))
	}
	const tableHead = "| Tier | Service | Coverage | Official | Ours beyond | Uncovered |\n| ---: | --- | --- | ---: | ---: | ---: |\n"
	b.WriteString(tableHead)
	var rest []svcRow
	for _, s := range covered {
		if r.tierOf(s.service) == 1 {
			b.WriteString(row(s))
		} else {
			rest = append(rest, s)
		}
	}
	if len(rest) > 0 {
		fmt.Fprintf(&b, "\n<details><summary>The %d tier 2 and 3 services with any coverage</summary>\n\n", len(rest))
		b.WriteString(tableHead)
		for _, s := range rest {
			b.WriteString(row(s))
		}
		b.WriteString("\n</details>\n")
	}
	fmt.Fprintf(&b, "\nServices are sorted by tier, then by attributes covered; blue is covered by ACK's released controllers, green by our kinds beyond ACK, grey by neither. The other %d services in the CloudFormation schemas are uncovered. Full data: [services.csv](docs/coverage/services.csv) (one row per service), [resources.csv](docs/coverage/resources.csv) (one row per resource) and [attributes.csv](docs/coverage/attributes.csv) (one row per attribute).\n\n", len(r.svcs)-len(covered))
	return b.String()
}

func commas(n int) string {
	s := fmt.Sprintf("%d", n)
	var out []byte
	for i, c := range []byte(s) {
		if i > 0 && (len(s)-i)%3 == 0 {
			out = append(out, ',')
		}
		out = append(out, c)
	}
	return string(out)
}
