package main

import (
	"fmt"
	"sort"
	"strings"
)

// rootSection is the text between the markers in the root README.md.
func rootSection(r *results) string {
	t := r.total
	var b strings.Builder
	b.WriteString("## Coverage\n\n")
	fmt.Fprintf(&b, "How much of AWS the official ACK controllers cover, and how much more this repository adds, counted in writable CloudFormation resource properties (\"attributes\") per service. Generated by `hack/coverage/run.sh`; the method, pinned sources and caveats are in [docs/coverage/README.md](docs/coverage/README.md).\n\n")
	fmt.Fprintf(&b, "![Total coverage: official %s%%, ours beyond official %s%%, uncovered %s%%](docs/coverage/bars/_total.svg)\n\n", pct1(t.attrOfficial, t.attrTotal), pct1(t.attrOursBeyond, t.attrTotal), pct1(t.attrUncov, t.attrTotal))
	fmt.Fprintf(&b, "Of %s attributes in %d resources across %d services, ACK covers %s (%s%%) and ours adds %s more (%s%%)",
		commas(t.attrTotal), t.resTotal, len(r.svcs), commas(t.attrOfficial), pct1(t.attrOfficial, t.attrTotal), commas(t.attrOursBeyond), pct1(t.attrOursBeyond, t.attrTotal))
	if t.oursBeyondPR > 0 {
		fmt.Fprintf(&b, ", %s of them copied from open upstream pull requests", commas(t.oursBeyondPR))
	}
	fmt.Fprintf(&b, ". ACK has a released kind for %d resources; ours adds %d resources ACK has none of.\n\n", t.resOfficial, t.resOursBeyond)

	var covered []svcRow
	for _, s := range r.svcs {
		if s.attrOfficial+s.attrOursBeyond > 0 || s.resOfficial+s.resOursBeyond > 0 {
			covered = append(covered, s)
		}
	}
	sort.SliceStable(covered, func(i, j int) bool {
		ci, cj := covered[i].attrOfficial+covered[i].attrOursBeyond, covered[j].attrOfficial+covered[j].attrOursBeyond
		if ci != cj {
			return ci > cj
		}
		return covered[i].service < covered[j].service
	})
	const head = 15
	row := func(s svcRow) string {
		return fmt.Sprintf("| `%s` | ![%s](docs/coverage/bars/%s.svg) | %s%% | %s%% | %s%% |\n", s.service, s.service, s.service,
			pct1(s.attrOfficial, s.attrTotal), pct1(s.attrOursBeyond, s.attrTotal), pct1(s.attrUncov, s.attrTotal))
	}
	const tableHead = "| Service | Coverage | Official | Ours beyond | Uncovered |\n| --- | --- | ---: | ---: | ---: |\n"
	b.WriteString(tableHead)
	for i, s := range covered {
		if i == head {
			break
		}
		b.WriteString(row(s))
	}
	if len(covered) > head {
		fmt.Fprintf(&b, "\n<details><summary>The other %d services with any coverage</summary>\n\n", len(covered)-head)
		b.WriteString(tableHead)
		for _, s := range covered[head:] {
			b.WriteString(row(s))
		}
		b.WriteString("\n</details>\n")
	}
	fmt.Fprintf(&b, "\nServices are sorted by attributes covered; blue is covered by ACK's released controllers, green by our kinds beyond ACK, grey by neither. The other %d services in the CloudFormation schemas are uncovered. Full data: [services.csv](docs/coverage/services.csv) (one row per service), [resources.csv](docs/coverage/resources.csv) (one row per resource) and [attributes.csv](docs/coverage/attributes.csv) (one row per attribute).\n\n", len(r.svcs)-len(covered))
	return b.String()
}

func commas(n int) string {
	s := fmt.Sprintf("%d", n)
	var out []byte
	for i, c := range []byte(s) {
		if i > 0 && (len(s)-i)%3 == 0 {
			out = append(out, ',')
		}
		out = append(out, c)
	}
	return string(out)
}
