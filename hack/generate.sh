# Regenerate every service's generated code with ACK's own generator, the
# way ACK's scripts/build-controller.sh does for one of its controllers:
#
#   1. ack-generate apis, then controller, from services/<svc>/generator.yaml,
#      services/<svc>/metadata.yaml and services/<svc>/templates (hook
#      templates), with --api-group-suffix aws.hfl.dev (patch 0001);
#   2. rewrite the generated imports of ACK's own controller module,
#      github.com/aws-controllers-k8s/<svc>-controller/, to ours,
#      github.com/highfivelabs/ack-extensions/services/<svc>/ (ACK's templates
#      hard-code the module path); imports of other ACK controllers stay;
#   3. replace every file carrying the generator's "DO NOT EDIT" header,
#      leaving hand-written files (hooks, hand-written kinds) alone;
#   4. controller-gen (the version ACK pins) for deepcopy, CRDs into
#      config/crds and the manager's RBAC into config/rbac;
#   5. gofmt and goimports.
#
# Needs hack/upstream.sh to have run, and network the first time a model is
# fetched (cached in .cache/ack-generate). `task check` fails if this
# changes anything that is committed.
set -o errexit -o nounset -o pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT}"
export GOTOOLCHAIN=local

SDK_VERSION="v1.34.0"         # UPSTREAM.md, "aws-sdk-go-v2 models"
# A service whose kind is a copy of an ACK controller's (docs/plan.md
# section 3, "Fixed copies of ACK's kinds") reads the models that
# controller was generated from, so the copy is identical (UPSTREAM.md).
SDK_VERSION_FOR() {
  case "$1" in
    autoscaling) echo "v1.41.5" ;; # autoscaling-controller v1.5.0's aws-sdk-go-v2 version
    cloudwatchlogs) echo "v1.41.5" ;; # cloudwatchlogs-controller v1.11.0's aws-sdk-go-v2 version
    ec2) echo "v1.41.5" ;;         # includes VolumeInitializationRate on LaunchTemplate EBS block devices
    efs) echo "v1.41.5" ;;         # efs-controller v1.9.0's aws-sdk-go-v2 version
    elasticache) echo "v1.41.5" ;; # matches go.mod aws-sdk-go-v2
    s3) echo "v1.41.5" ;;          # s3-controller v1.15.0's ack-generate-metadata.yaml
    *) echo "${SDK_VERSION}" ;;
  esac
}
GROUP_SUFFIX="aws.hfl.dev"
SERVICES=(applicationautoscaling autoscaling cloudtrail cloudwatchlogs ec2 ecr efs elasticache eventbridge iam kms lambda organizations rds s3 s3control scheduler wafv2)
GEN="${ROOT}/bin/ack-generate"
CONTROLLER_GEN="${ROOT}/bin/controller-gen"
GOIMPORTS="${ROOT}/bin/goimports"
HEADER="Code generated by ack-generate. DO NOT EDIT."
BOILERPLATE="${ROOT}/third_party/code-generator/templates/boilerplate.txt"

for tool in "${GEN}" "${CONTROLLER_GEN}" "${GOIMPORTS}"; do
  [[ -x "${tool}" ]] || { echo "${tool} is missing; run task tools (and hack/upstream.sh)" >&2; exit 1; }
done

work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

for svc in "${SERVICES[@]}"; do
  src="services/${svc}"
  out="${work}/${svc}"
  mkdir -p "${out}"
  common=(
    "${svc}" -o "${out}"
    --aws-sdk-go-version "$(SDK_VERSION_FOR "${svc}")"
    --api-group-suffix "${GROUP_SUFFIX}"
    --cache-dir "${ROOT}/.cache/ack-generate"
    --generator-config-path "${src}/generator.yaml"
    --metadata-config-path "${src}/metadata.yaml"
    --template-dirs "third_party/code-generator/templates,${src}/templates"
    --service-account-name "ack-extensions-${svc}-manager"
  )
  "${GEN}" apis "${common[@]}" >/dev/null
  "${GEN}" controller "${common[@]}" >/dev/null

  # 2. Our module path for this service's own generated packages.
  { grep -rl "github.com/aws-controllers-k8s/${svc}-controller/" "${out}" || true; } | while IFS= read -r f; do
    perl -pi -e "s#github.com/aws-controllers-k8s/${svc}-controller/#github.com/highfivelabs/ack-extensions/services/${svc}/#g" "${f}"
  done
  # AutoScalingGroup's launchTemplateRef targets ack-extensions's ec2.aws.hfl.dev
  # LaunchTemplate, while Instance and CapacityReservation stay on ACK's
  # ec2-controller (ec2.services.k8s.aws). Also preserve per-tag PropagateAtLaunch
  # across EnsureTags/FilterSystemTags.
  if [[ "${svc}" == "autoscaling" ]]; then
    ref_file="${out}/pkg/resource/auto_scaling_group/references.go"
    if [[ -f "${ref_file}" ]]; then
      perl -0777 -pi -e 's#ec2apitypes "github.com/aws-controllers-k8s/ec2-controller/apis/v1alpha1"#ec2apitypes "github.com/aws-controllers-k8s/ec2-controller/apis/v1alpha1"\n\thflec2apitypes "github.com/highfivelabs/ack-extensions/services/ec2/apis/v1alpha1"#g; s#ec2apitypes\.LaunchTemplate#hflec2apitypes.LaunchTemplate#g' "${ref_file}"
    fi
    mgr_file="${out}/pkg/resource/auto_scaling_group/manager.go"
    if [[ -f "${mgr_file}" ]]; then
      perl -pi -e 's#r\.ko\.Spec\.Tags = fromACKTags\([^)]+\)#$&\n\tpreserveTagPropagateAtLaunch(existingTags, r.ko.Spec.Tags)#g; s#a\.ko\.Spec\.Tags = fromACKTags\([^)]+\)#$&\n\tpreserveTagPropagateAtLaunch(existingDesiredTags, a.ko.Spec.Tags)#g' "${mgr_file}"
    fi
  fi
  if [[ "${svc}" == "elasticache" ]]; then
    for ref_file in "${out}/cmd/controller/main.go" "${out}/pkg/resource/cache_cluster/references.go" "${out}/pkg/resource/replication_group/references.go"; do
      if [[ -f "${ref_file}" ]]; then
        perl -pi -e 's#"github\.com/aws-controllers-k8s/sns-controller/apis/v1alpha1"#"github.com/highfivelabs/ack-extensions/services/elasticache/pkg/ackmirrors"#g; s#\bsvcapitypes\.(CacheParameterGroup|CacheSubnetGroup|Snapshot|UserGroup)\b#snsapitypes.$1#g' "${ref_file}"
      fi
    done
  fi

  # 3. Drop what was generated before, keep what was written by hand.
  if [[ -d "${src}" ]]; then
    { grep -rl --include='*.go' "${HEADER}" "${src}" || true; } | while IFS= read -r f; do rm -f "${f}"; done
  fi
  mkdir -p "${src}/apis/v1alpha1" "${src}/cmd/controller" "${src}/pkg"
  find "${out}/apis/v1alpha1" -name '*.go' -exec cp {} "${src}/apis/v1alpha1/" \;
  cp "${out}/cmd/controller/main.go" "${src}/cmd/controller/main.go"
  (cd "${out}/pkg" && find . -name '*.go') | while IFS= read -r f; do
    mkdir -p "${src}/pkg/$(dirname "${f}")"
    cp "${out}/pkg/${f}" "${src}/pkg/${f}"
  done
done

# 4. controller-gen over every service at once.
apis=()
resources=()
for svc in "${SERVICES[@]}"; do
  apis+=("paths=./services/${svc}/apis/...")
  resources+=("${svc}")
done
"${CONTROLLER_GEN}" object:headerFile="${BOILERPLATE}" "${apis[@]}"
rm -rf config/crds/bases
mkdir -p config/crds/bases
"${CONTROLLER_GEN}" crd:allowDangerousTypes=true "${apis[@]}" output:crd:artifacts:config=config/crds/bases
mkdir -p config/rbac
for svc in "${SERVICES[@]}"; do
  rbac="${work}/rbac-${svc}"
  "${CONTROLLER_GEN}" rbac:roleName="ack-extensions-${svc}-manager" "paths=./services/${svc}/pkg/..." output:rbac:artifacts:config="${rbac}"
  cp "${rbac}/role.yaml" "config/rbac/${svc}-manager-role.yaml"
done

# 5. Format as ACK does.
gofmt -w services
"${GOIMPORTS}" -w services
echo "generated: ${SERVICES[*]} (CRDs in config/crds/bases, manager roles in config/rbac)"
