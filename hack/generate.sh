# Regenerate every service's generated code with ACK's own generator, the
# way ACK's scripts/build-controller.sh does for one of its controllers:
#
#   1. ack-generate apis, then controller, from services/<svc>/generator.yaml,
#      services/<svc>/metadata.yaml and services/<svc>/templates (hook
#      templates), with --api-group-suffix aws.hfl.dev (patch 0001);
#   2. rewrite the generated imports of ACK's own controller module,
#      github.com/aws-controllers-k8s/<svc>-controller/, to ours,
#      github.com/highfivelabs/ack-extensions/services/<svc>/ (ACK's templates
#      hard-code the module path); imports of other ACK controllers stay;
#   3. replace every file carrying the generator's "DO NOT EDIT" header,
#      leaving hand-written files (hooks, hand-written kinds) alone;
#   4. controller-gen (the version ACK pins) for deepcopy, CRDs into
#      config/crds and the manager's RBAC into config/rbac;
#   5. gofmt and goimports.
#
# Needs hack/upstream.sh to have run, and network the first time a model is
# fetched (cached in .cache/ack-generate). `make check` fails if this
# changes anything that is committed.
set -o errexit -o nounset -o pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT}"
export GOTOOLCHAIN=local

SDK_VERSION="v1.34.0"         # UPSTREAM.md, "aws-sdk-go-v2 models"
GROUP_SUFFIX="aws.hfl.dev"
SERVICES=(autoscaling ec2 iam kms lambda rds)
GEN="${ROOT}/bin/ack-generate"
CONTROLLER_GEN="${ROOT}/bin/controller-gen"
GOIMPORTS="${ROOT}/bin/goimports"
HEADER="Code generated by ack-generate. DO NOT EDIT."
BOILERPLATE="${ROOT}/third_party/code-generator/templates/boilerplate.txt"

for tool in "${GEN}" "${CONTROLLER_GEN}" "${GOIMPORTS}"; do
  [[ -x "${tool}" ]] || { echo "${tool} is missing; run make tools (and hack/upstream.sh)" >&2; exit 1; }
done

work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

for svc in "${SERVICES[@]}"; do
  src="services/${svc}"
  out="${work}/${svc}"
  mkdir -p "${out}"
  common=(
    "${svc}" -o "${out}"
    --aws-sdk-go-version "${SDK_VERSION}"
    --api-group-suffix "${GROUP_SUFFIX}"
    --cache-dir "${ROOT}/.cache/ack-generate"
    --generator-config-path "${src}/generator.yaml"
    --metadata-config-path "${src}/metadata.yaml"
    --template-dirs "third_party/code-generator/templates,${src}/templates"
    --service-account-name "ack-extensions-${svc}-manager"
  )
  "${GEN}" apis "${common[@]}" >/dev/null
  "${GEN}" controller "${common[@]}" >/dev/null

  # 2. Our module path for this service's own generated packages.
  { grep -rl "github.com/aws-controllers-k8s/${svc}-controller/" "${out}" || true; } | while IFS= read -r f; do
    perl -pi -e "s#github.com/aws-controllers-k8s/${svc}-controller/#github.com/highfivelabs/ack-extensions/services/${svc}/#g" "${f}"
  done

  # 3. Drop what was generated before, keep what was written by hand.
  if [[ -d "${src}" ]]; then
    { grep -rl --include='*.go' "${HEADER}" "${src}" || true; } | while IFS= read -r f; do rm -f "${f}"; done
  fi
  mkdir -p "${src}/apis/v1alpha1" "${src}/cmd/controller" "${src}/pkg"
  find "${out}/apis/v1alpha1" -name '*.go' -exec cp {} "${src}/apis/v1alpha1/" \;
  cp "${out}/cmd/controller/main.go" "${src}/cmd/controller/main.go"
  (cd "${out}/pkg" && find . -name '*.go') | while IFS= read -r f; do
    mkdir -p "${src}/pkg/$(dirname "${f}")"
    cp "${out}/pkg/${f}" "${src}/pkg/${f}"
  done
done

# 4. controller-gen over every service at once.
apis=()
resources=()
for svc in "${SERVICES[@]}"; do
  apis+=("paths=./services/${svc}/apis/...")
  resources+=("${svc}")
done
"${CONTROLLER_GEN}" object:headerFile="${BOILERPLATE}" "${apis[@]}"
rm -rf config/crds/bases
mkdir -p config/crds/bases
"${CONTROLLER_GEN}" crd:allowDangerousTypes=true "${apis[@]}" output:crd:artifacts:config=config/crds/bases
mkdir -p config/rbac
for svc in "${SERVICES[@]}"; do
  rbac="${work}/rbac-${svc}"
  "${CONTROLLER_GEN}" rbac:roleName="ack-extensions-${svc}-manager" "paths=./services/${svc}/pkg/resource/..." output:rbac:artifacts:config="${rbac}"
  cp "${rbac}/role.yaml" "config/rbac/${svc}-manager-role.yaml"
done

# 5. Format as ACK does.
gofmt -w services
"${GOIMPORTS}" -w services
echo "generated: ${SERVICES[*]} (CRDs in config/crds/bases, manager roles in config/rbac)"
